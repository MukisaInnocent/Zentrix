// Generates server/migrations/0002_reference_data.sql from vetted public datasets (dev dependencies only).
// Run with: npm run gen:reference-data. The output is committed and reviewed like any migration.
import { writeFileSync } from 'node:fs';
import path from 'node:path';
import ct from 'countries-and-timezones';
import { countries } from 'countries-list';
import currencyCodes from 'currency-codes';
import { getCountries, getCountryCallingCode, type CountryCode } from 'libphonenumber-js';
import { MIGRATIONS_DIR } from '../src/lib/paths.js';

// Not money: precious metals, funds, testing and settlement units.
const EXCLUDED_CURRENCIES = new Set([
  'XAU', 'XAG', 'XPD', 'XPT', 'XDR', 'XSU', 'XUA', 'XBA', 'XBB', 'XBC', 'XBD', 'XTS', 'XXX',
  'BOV', 'CHE', 'CHW', 'CLF', 'COU', 'MXV', 'USN', 'UYI', 'UYW', 'VED',
]);
// ISO 4217 codes missing from the currency-codes package.
const SUPPLEMENT_CURRENCIES = [{ code: 'XCG', number: '532', digits: 2, currency: 'Caribbean Guilder' }];
// Explicit wallet-currency overrides for countries that use another currency in practice
// (section 1 of the master prompt). TODO(owner): review before live.
const CURRENCY_OVERRIDES: Record<string, string> = {
  ZW: 'USD', EC: 'USD', SV: 'USD', PA: 'USD', TL: 'USD', ME: 'EUR', XK: 'EUR', PS: 'ILS', BT: 'BTN',
  LS: 'LSL', NA: 'NAD', SZ: 'SZL', CU: 'CUP', HT: 'HTG', KH: 'KHR', LR: 'LRD',
};
// Default time zone where the capital does not name a zone. Members pick their own zone at sign-up.
const TIMEZONE_OVERRIDES: Record<string, string> = {
  US: 'America/New_York', CA: 'America/Toronto', BR: 'America/Sao_Paulo', RU: 'Europe/Moscow',
  AU: 'Australia/Sydney', CN: 'Asia/Shanghai', IN: 'Asia/Kolkata', CD: 'Africa/Kinshasa', KZ: 'Asia/Almaty',
  NZ: 'Pacific/Auckland', EC: 'America/Guayaquil', PF: 'Pacific/Tahiti', KI: 'Pacific/Tarawa',
  FM: 'Pacific/Pohnpei', UA: 'Europe/Kyiv', CH: 'Europe/Zurich', DE: 'Europe/Berlin', NG: 'Africa/Lagos',
  ZA: 'Africa/Johannesburg', TZ: 'Africa/Dar_es_Salaam', VN: 'Asia/Ho_Chi_Minh', TR: 'Europe/Istanbul',
  MA: 'Africa/Casablanca', PK: 'Asia/Karachi', AE: 'Asia/Dubai', MX: 'America/Mexico_City',
  ID: 'Asia/Jakarta', AR: 'America/Argentina/Buenos_Aires', CL: 'America/Santiago', MN: 'Asia/Ulaanbaatar',
  ES: 'Europe/Madrid', PT: 'Europe/Lisbon', MY: 'Asia/Kuala_Lumpur', GL: 'America/Nuuk',
};
// Placeholder sanctions blocklist (decision D25). Not legal advice. TODO(owner).
const BLOCK_REASON = 'placeholder sanctions list, TODO(owner)';
const BLOCKED = new Set(['KP', 'IR', 'CU']);

const sql = (v: string | number | boolean | null): string =>
  v === null ? 'NULL' : typeof v === 'string' ? `'${v.replace(/'/g, "''")}'` : String(v);

const currencies = [...currencyCodes.data, ...SUPPLEMENT_CURRENCIES]
  .filter(c => !EXCLUDED_CURRENCIES.has(c.code) && /^[A-Z]{3}$/.test(c.code))
  .sort((a, b) => a.code.localeCompare(b.code));
const currencySet = new Set(currencies.map(c => c.code));

const phoneCountries = new Set<string>(getCountries());
const regionNames = new Intl.DisplayNames(['en'], { type: 'region' });
const rows: string[] = [];
const report: string[] = [];
for (const [code, info] of Object.entries(countries).sort(([a], [b]) => a.localeCompare(b))) {
  if (!phoneCountries.has(code)) {
    report.push(`skip ${code}: no phone numbering plan`);
    continue;
  }
  const listed = (info.currency as string[]).find(c => currencySet.has(c));
  const currency = CURRENCY_OVERRIDES[code] ?? listed;
  if (!currency || !currencySet.has(currency)) {
    report.push(`skip ${code}: no usable currency (${(info.currency as string[]).join(',')})`);
    continue;
  }
  const zones = ct.getTimezonesForCountry(code, { deprecated: true })?.map(z => z.name) ?? [];
  const capital = (info.capital || '').replace(/ /g, '_');
  const timezone =
    TIMEZONE_OVERRIDES[code] ??
    zones.find(z => capital !== '' && z.endsWith(`/${capital}`)) ??
    zones.find(z => ct.getTimezone(z)?.countries.join() === code) ??
    ct.getCountry(code)?.timezones[0] ??
    'UTC';
  if (zones.length > 2) report.push(`${code}: ${zones.length} zones, default ${timezone}`);
  const name = regionNames.of(code) ?? info.name;
  const dial = getCountryCallingCode(code as CountryCode);
  const locale = Intl.getCanonicalLocales(`en-${code}`)[0] ?? 'en';
  const blocked = BLOCKED.has(code);
  const values = [code, name, currency, dial, locale, timezone, blocked, blocked ? BLOCK_REASON : null];
  rows.push(`  (${values.map(sql).join(', ')})`);
}

const out = `-- Generated by server/scripts/gen-reference-data.ts. Do not edit by hand: regenerate and review.
-- Sources: currency-codes (ISO 4217 with minor-unit exponents), countries-list, countries-and-timezones,
-- libphonenumber-js calling codes, and Intl.DisplayNames for English country names.

-- Up Migration

CREATE TABLE currencies (
  code char(3) PRIMARY KEY CHECK (code ~ '^[A-Z]{3}$'),
  numeric_code char(3),
  name text NOT NULL,
  exponent smallint NOT NULL CHECK (exponent BETWEEN 0 AND 4),
  enabled boolean NOT NULL DEFAULT true
);
COMMENT ON TABLE currencies IS 'ISO 4217 currencies. exponent = minor-unit digits (UGX 0, USD 2, KWD 3). Money is stored as BIGINT minor units.';

CREATE TABLE countries (
  code char(2) PRIMARY KEY CHECK (code ~ '^[A-Z]{2}$'),
  name text NOT NULL,
  currency_code char(3) NOT NULL REFERENCES currencies (code),
  dial_code text NOT NULL CHECK (dial_code ~ '^[0-9]{1,4}$'),
  default_locale text NOT NULL,
  default_timezone text NOT NULL,
  blocked boolean NOT NULL DEFAULT false,
  block_reason text,
  live_enabled boolean NOT NULL DEFAULT false,
  updated_at timestamptz NOT NULL DEFAULT now(),
  CHECK (NOT blocked OR block_reason IS NOT NULL),
  CHECK (NOT (blocked AND live_enabled))
);
COMMENT ON COLUMN countries.blocked IS 'Sanctions or restricted-country blocklist. Blocks sign-up and payouts in both modes (decision D25).';
COMMENT ON COLUMN countries.live_enabled IS 'Live mode only: an admin switches a country on (owner decision of 2026-10-21, no legal-review gate).';

CREATE TRIGGER countries_touch BEFORE UPDATE ON countries FOR EACH ROW EXECUTE FUNCTION zx_touch_updated_at();

INSERT INTO currencies (code, numeric_code, name, exponent) VALUES
${currencies.map(c => `  (${[c.code, c.number, c.currency, c.digits].map(sql).join(', ')})`).join(',\n')};

INSERT INTO countries (code, name, currency_code, dial_code, default_locale, default_timezone, blocked, block_reason) VALUES
${rows.join(',\n')};

-- Down Migration

DROP TABLE countries;
DROP TABLE currencies;
`;
const target = path.join(MIGRATIONS_DIR, '0002_reference_data.sql');
writeFileSync(target, out);
console.log(`Wrote ${target}: ${currencies.length} currencies, ${rows.length} countries.`);
console.log(report.join('\n'));
