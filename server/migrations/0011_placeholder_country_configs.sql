CREATE FUNCTION pg_temp.zx_round2(x numeric) RETURNS numeric LANGUAGE sql IMMUTABLE AS $$
  SELECT CASE WHEN x <= 0 THEN 0 ELSE round(x / power(10::numeric, floor(log(x)) - 1)) * power(10::numeric, floor(log(x)) - 1) END
$$;

